import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../docs/casino-forensic-completion-2026-07-29.json', import.meta.url);
const destination = new URL('../migrations/0056_casino_forensic_completion.sql', import.meta.url);
const document = JSON.parse(readFileSync(source, 'utf8'));
const payload = JSON.stringify(document).replaceAll("'", "''");

const sql = `-- Generated by scripts/render-casino-forensic-completion-migration.mjs.
-- The temporary table makes the four completion updates deterministic and replay-safe.

DROP TABLE IF EXISTS casino_forensic_completion_0056;
CREATE TEMP TABLE casino_forensic_completion_0056 (
  case_id TEXT PRIMARY KEY,
  analysis TEXT NOT NULL CHECK (json_valid(analysis))
);

-- canonical-payload-start
WITH completion_payload(document) AS (
  VALUES ('${payload}')
)
INSERT OR REPLACE INTO casino_forensic_completion_0056 (case_id, analysis)
SELECT
  json_extract(value, '$.case_id'),
  json_extract(value, '$.forensic_analysis')
FROM completion_payload, json_each(completion_payload.document, '$.cases');
-- canonical-payload-end

UPDATE casino_syntheses
SET outlook = json_set(
      COALESCE(NULLIF(outlook, ''), '{}'),
      '$.forensic_analysis',
      json((
        SELECT analysis
        FROM casino_forensic_completion_0056 AS completion
        WHERE completion.case_id = casino_syntheses.case_id
      ))
    ),
    reviewed_at = '2026-07-29'
WHERE EXISTS (
  SELECT 1
  FROM casino_forensic_completion_0056 AS completion
  WHERE completion.case_id = casino_syntheses.case_id
);

DROP TABLE IF EXISTS casino_forensic_completion_0056;
`;

writeFileSync(fileURLToPath(destination), sql);
console.log(fileURLToPath(destination));
