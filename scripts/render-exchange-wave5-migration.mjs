import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../docs/exchange-wave5-2026-07-29.json', import.meta.url);
const destination = new URL('../migrations/0052_exchange_wave5_forensic_analysis.sql', import.meta.url);
const document = JSON.parse(readFileSync(source, 'utf8'));
const payload = JSON.stringify(document).replaceAll("'", "''");

const sql = `-- Generated by scripts/render-exchange-wave5-migration.mjs from the cited Wave-5 corpus.
-- The temporary table makes all three exchange-tier updates deterministic and replay-safe.

DROP TABLE IF EXISTS exchange_wave5_forensic_0052;
CREATE TEMP TABLE exchange_wave5_forensic_0052 (
  target_table TEXT NOT NULL,
  kind TEXT NOT NULL,
  slug TEXT NOT NULL,
  analysis TEXT NOT NULL,
  PRIMARY KEY (target_table, kind, slug)
);

-- canonical-payload-start
WITH wave5_payload(document) AS (
  VALUES ('${payload}')
)
INSERT OR REPLACE INTO exchange_wave5_forensic_0052 (target_table, kind, slug, analysis)
SELECT
  json_extract(value, '$.table'),
  json_extract(value, '$.kind'),
  json_extract(value, '$.slug'),
  json_extract(value, '$.forensic_analysis')
FROM wave5_payload, json_each(wave5_payload.document, '$.cases');
-- canonical-payload-end

UPDATE successful_exchanges
SET profile = json_set(
      COALESCE(NULLIF(profile, ''), '{}'),
      '$.forensic_analysis',
      json((
        SELECT analysis
        FROM exchange_wave5_forensic_0052 AS wave
        WHERE wave.target_table = 'successful_exchanges'
          AND wave.kind = successful_exchanges.type
          AND wave.slug = successful_exchanges.slug
      ))
    ),
    updated_at = '2026-07-29'
WHERE EXISTS (
  SELECT 1
  FROM exchange_wave5_forensic_0052 AS wave
  WHERE wave.target_table = 'successful_exchanges'
    AND wave.kind = successful_exchanges.type
    AND wave.slug = successful_exchanges.slug
);

UPDATE mid_exchanges
SET profile = json_set(
      COALESCE(NULLIF(profile, ''), '{}'),
      '$.forensic_analysis',
      json((
        SELECT analysis
        FROM exchange_wave5_forensic_0052 AS wave
        WHERE wave.target_table = 'mid_exchanges'
          AND wave.kind = mid_exchanges.kind
          AND wave.slug = mid_exchanges.slug
      ))
    ),
    updated_at = '2026-07-29'
WHERE EXISTS (
  SELECT 1
  FROM exchange_wave5_forensic_0052 AS wave
  WHERE wave.target_table = 'mid_exchanges'
    AND wave.kind = mid_exchanges.kind
    AND wave.slug = mid_exchanges.slug
);

UPDATE dead_exchanges
SET profile = json_set(
      COALESCE(NULLIF(profile, ''), '{}'),
      '$.forensic_analysis',
      json((
        SELECT analysis
        FROM exchange_wave5_forensic_0052 AS wave
        WHERE wave.target_table = 'dead_exchanges'
          AND wave.kind = dead_exchanges.kind
          AND wave.slug = dead_exchanges.slug
      ))
    ),
    updated_at = '2026-07-29'
WHERE EXISTS (
  SELECT 1
  FROM exchange_wave5_forensic_0052 AS wave
  WHERE wave.target_table = 'dead_exchanges'
    AND wave.kind = dead_exchanges.kind
    AND wave.slug = dead_exchanges.slug
);

DROP TABLE IF EXISTS exchange_wave5_forensic_0052;
`;

writeFileSync(fileURLToPath(destination), sql);
