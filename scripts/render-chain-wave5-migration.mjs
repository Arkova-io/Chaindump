import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../docs/top50-chain-dossiers-wave5-2026-07-29.json', import.meta.url);
const destination = new URL('../migrations/0044_chain_dossiers_wave5.sql', import.meta.url);
const dossiers = JSON.parse(readFileSync(source, 'utf8'));
const payload = JSON.stringify(dossiers).replaceAll("'", "''");

const sql = `-- Generated by scripts/render-chain-wave5-migration.mjs from the cited wave-five dossier corpus.
-- Re-run the generator after changing the source JSON; INSERT OR REPLACE keeps application idempotent.

WITH dossier_seed(payload) AS (
  VALUES ('${payload}')
),
dossiers AS (
  SELECT value AS dossier FROM dossier_seed, json_each(dossier_seed.payload)
),
dimension_rows AS (
  SELECT
    json_extract(dossier, '$.chain') AS chain,
    dimensions.key AS dimension,
    dimensions.value AS data,
    (SELECT json_group_array(json(json_extract(dossier, '$.source_catalog.' || source_keys.value)))
     FROM json_each(json_extract(dossier, '$.dimension_sources.' || dimensions.key)) AS source_keys) AS sources
  FROM dossiers, json_each(json_extract(dossier, '$.dimensions')) AS dimensions
),
meta_rows AS (
  SELECT
    json_extract(dossier, '$.chain') AS chain,
    '_meta' AS dimension,
    json_extract(dossier, '$.meta') AS data,
    (SELECT json_group_array(json(value))
     FROM json_each(json_extract(dossier, '$.source_catalog'))) AS sources
  FROM dossiers
)
INSERT OR REPLACE INTO chain_facts (chain, dimension, data, sources, updated_at)
SELECT chain, dimension, data, sources, '2026-07-29' FROM dimension_rows
UNION ALL
SELECT chain, dimension, data, sources, '2026-07-29' FROM meta_rows;
`;

writeFileSync(fileURLToPath(destination), sql);
