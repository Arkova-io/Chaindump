#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { validateForensicAnalysis } from '../src/lib/forensic-analysis.js';
import { validateForensicFreshness } from '../src/lib/evidence-freshness.mjs';
import { validateFieldCitedNft } from '../src/lib/nft-citation.mjs';

const sourceUrl = new URL('../docs/nft-legacy-depth-wave-2026-07-29.json', import.meta.url);
const destinationUrl = new URL('../migrations/0054_nft_legacy_depth_refresh.sql', import.meta.url);

function quoteSql(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function sourceResolver(dossier) {
  return Object.fromEntries(dossier.sources.map((source) => [source.id, source]));
}

function validateDocument(document) {
  if (document?.schema !== 'chaindump-nft-patch-v1') {
    throw new Error('Unexpected NFT patch schema');
  }
  if (!Array.isArray(document.dossiers) || !document.dossiers.length) {
    throw new Error('No NFT patch dossiers');
  }
  const slugs = new Set();
  for (const dossier of document.dossiers) {
    if (!dossier.slug || slugs.has(dossier.slug)) {
      throw new Error(`Missing or duplicate dossier slug: ${dossier.slug || '(missing)'}`);
    }
    slugs.add(dossier.slug);
    const fieldCitations = validateFieldCitedNft(dossier.profile_patch, dossier.sources);
    if (!fieldCitations.valid) {
      throw new Error(`${dossier.slug} citations: ${fieldCitations.errors.join('; ')}`);
    }
    const freshness = validateForensicFreshness({
      status: dossier.status,
      profile: dossier.profile_patch,
      sources: dossier.sources,
    });
    if (!freshness.valid) {
      throw new Error(`${dossier.slug} freshness: ${freshness.errors.join('; ')}`);
    }
    const forensic = validateForensicAnalysis(dossier.profile_patch.forensic_analysis, {
      resolver: sourceResolver(dossier),
    });
    if (forensic.errors.length || forensic.warnings.length || forensic.withheld_sections.length) {
      throw new Error(`${dossier.slug} forensic analysis: ${[
        ...forensic.errors,
        ...forensic.warnings,
        ...forensic.withheld_sections,
      ].join('; ')}`);
    }
  }
}

export function renderNftLegacyDepthMigration(document) {
  validateDocument(document);
  const payload = quoteSql(JSON.stringify(document));
  const updatedAt = quoteSql(document.research_as_of);
  return `-- Generated by scripts/render-nft-legacy-depth-migration.mjs.
-- Applies field-cited patches so the existing long-form legacy narratives are retained.

DROP TABLE IF EXISTS nft_legacy_depth_0054;
CREATE TEMP TABLE nft_legacy_depth_0054 (
  slug TEXT PRIMARY KEY,
  status TEXT NOT NULL,
  profile_patch TEXT NOT NULL,
  sources TEXT NOT NULL
);

-- canonical-payload-start
WITH legacy_depth_payload(document) AS (
  VALUES (${payload})
)
INSERT OR REPLACE INTO nft_legacy_depth_0054 (slug, status, profile_patch, sources)
SELECT
  json_extract(value, '$.slug'),
  json_extract(value, '$.status'),
  json_extract(value, '$.profile_patch'),
  json_extract(value, '$.sources')
FROM legacy_depth_payload, json_each(legacy_depth_payload.document, '$.dossiers');
-- canonical-payload-end

UPDATE nft_collections
SET status = (
      SELECT patch.status
      FROM nft_legacy_depth_0054 AS patch
      WHERE patch.slug = nft_collections.slug
    ),
    profile = json_patch(
      COALESCE(NULLIF(profile, ''), '{}'),
      json((
        SELECT patch.profile_patch
        FROM nft_legacy_depth_0054 AS patch
        WHERE patch.slug = nft_collections.slug
      ))
    ),
    sources = (
      SELECT patch.sources
      FROM nft_legacy_depth_0054 AS patch
      WHERE patch.slug = nft_collections.slug
    ),
    updated_at = ${updatedAt}
WHERE EXISTS (
  SELECT 1
  FROM nft_legacy_depth_0054 AS patch
  WHERE patch.slug = nft_collections.slug
);

DROP TABLE IF EXISTS nft_legacy_depth_0054;
`;
}

function main() {
  const document = JSON.parse(readFileSync(sourceUrl, 'utf8'));
  writeFileSync(fileURLToPath(destinationUrl), renderNftLegacyDepthMigration(document));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
